-- =====================================================================
-- V1: Initial Khaata schema.
-- Written in portable SQL that runs on both H2 (PostgreSQL mode) and
-- real PostgreSQL, so dev and prod share one migration.
-- =====================================================================

-- A "page" in the paper khaata: one row per customer.
CREATE TABLE customer (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120)  NOT NULL,
    phone           VARCHAR(20)   NOT NULL,
    email           VARCHAR(160),
    customer_type   VARCHAR(16)   NOT NULL,          -- REGULAR | NORMAL
    due_window_days INT           NOT NULL,          -- 7 / 15 / 30
    created_at      TIMESTAMP     NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0, -- optimistic locking
    CONSTRAINT uq_customer_phone UNIQUE (phone)
);

-- APPEND-ONLY ledger. Rows are inserted, never updated or deleted.
-- Balance is DERIVED: SUM(CREDIT) - SUM(REPAYMENT). This gives a full
-- auditable history and avoids lost-update concurrency bugs on a balance column.
CREATE TABLE ledger_transaction (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT         NOT NULL REFERENCES customer(id),
    type        VARCHAR(16)    NOT NULL,             -- CREDIT | REPAYMENT
    amount      DECIMAL(12,2)  NOT NULL,             -- always positive; sign comes from type
    note        VARCHAR(255),
    due_date    DATE,                                -- set for CREDIT rows
    created_at  TIMESTAMP      NOT NULL,
    CONSTRAINT chk_amount_positive CHECK (amount > 0)
);

CREATE INDEX idx_txn_customer ON ledger_transaction (customer_id);
CREATE INDEX idx_txn_due_date ON ledger_transaction (due_date);

-- Record of every reminder attempt. Makes the reminder job IDEMPOTENT
-- ("already reminded this customer today?") and provides an audit trail.
CREATE TABLE reminder_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT       NOT NULL REFERENCES customer(id),
    channel     VARCHAR(16)  NOT NULL,               -- CONSOLE | WHATSAPP | SMS
    status      VARCHAR(16)  NOT NULL,               -- SENT | FAILED | SKIPPED
    message     VARCHAR(500),
    sent_on     DATE         NOT NULL,               -- used for the "today?" dedupe check
    created_at  TIMESTAMP    NOT NULL
);

CREATE INDEX idx_reminder_customer_day ON reminder_log (customer_id, sent_on);
